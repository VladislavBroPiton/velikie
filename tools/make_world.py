# Проекция: равнопромежуточная, широты от 78 до -56
W, H = 1000, 500
LAT0, LAT1 = 78, -56
def xy(lat, lon):
    x = (lon + 180) / 360 * W
    y = (LAT0 - lat) / (LAT0 - LAT1) * H
    return round(x, 1), round(y, 1)

def inside(pt, ring):
    x, y = pt; c = False; n = len(ring)
    for i in range(n):
        x1, y1 = ring[i]; x2, y2 = ring[i - 1]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            c = not c
    return c

def main(geo):
    feats = json.load(open(geo, encoding="utf-8"))["features"]
    polys = []
    for f in feats:
        g = f["geometry"]
        rings = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for poly in rings:
            outer = poly[0]
            xs = [p[0] for p in outer]; ys = [p[1] for p in outer]
            polys.append((min(xs), max(xs), min(ys), max(ys), outer))
    step = 2.0  # градусов между точками
    dots = []
    lat = LAT0 - step / 2
    row = 0
    while lat > LAT1:
        lon = -180 + step / 2 + (step / 2 if row % 2 else 0)
        while lon < 180:
            for x0, x1, y0, y1, ring in polys:
                if x0 <= lon <= x1 and y0 <= lat <= y1 and inside((lon, lat), ring):
                    dots.append(xy(lat, lon)); break
            lon += step
        lat -= step * 0.87; row += 1
    # каждая точка — отрезок нулевой длины с круглым концом: так файл в разы меньше
    path = "".join(f"M{x:g} {y:g}h0" for x, y in dots)
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}"><path stroke="#3d3729" stroke-width="3.6" stroke-linecap="round" d="{path}"/></svg>'
    (ROOT / "data" / "map.svg").write_text(svg, encoding="utf-8")
    people = json.load(open(ROOT / "data" / "people.json", encoding="utf-8"))
    miss = [p["id"] for p in people if p["id"] not in BIRTH]
    assert not miss, miss
    world = {pid: {"place": c, "x": xy(la, lo)[0], "y": xy(la, lo)[1]} for pid, (c, la, lo) in BIRTH.items()}
    json.dump(world, open(ROOT / "data" / "world.json", "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    print(len(dots), "точек,", len(world), "героев, map.svg", len(svg) // 1024, "КБ")

if __name__ == "__main__":
    main(sys.argv[1])
